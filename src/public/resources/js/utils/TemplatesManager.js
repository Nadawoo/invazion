/**
 * Loader for the <templates> located in /resources/templates/xxxx.html
 * 
 * Features:
 *      automatic download upon first access;
 *      a single fetch() per file, even if multiple calls arrive in parallel;
 *      HTML parsed only once;
 *      constant-time template lookup (Map);
 *      explicit error if a requested template does not exist;
 *      detection of templates missing an ID or having duplicate IDs.
 *      
 * Example of usage:
 *      import { TemplatesManager } from "./utils/TemplatesManager.js";
 *      const fragment = await TemplatesManager.instantiate("ui", "dialog");
 *      document.querySelector("#myContainer").appendChild(fragment);
 *      
 * NB: Do not instantiate this class with `new`. All members are static and the cache 
 * is shared automatically.
 * 
 * If you got a message "template #xxxx not found" although it is in your .html file,
 * check that the .html file is not an obsolete cached version.
 * 
 * AI transparency policy: This class was primarily generated by ChatGPT
 * then validated by a human.
 */
export class TemplatesManager {
    
    static #cache    = new Map();
    static #loading  = new Map();
    static #basePath = "./templates";

    
    constructor() {
        
        throw new Error(
            "TemplatesManager is a static class and cannot be instantiated."
        );
    }


    /**
     * Preloads one or more template files. This avoids network requests 
     * the first time a template is used.
     * 
     * Usage :
     *    await TemplatesManager.preload(
     *       "ui",
     *       "dialogs",
     *       "inventory",
     *       "hud"
     *    );
     *
     * @param {...string} fileNames Template file names without the ".html" extension.
     * @returns {Promise<void>}
     */
    static async preload(...fileNames) {

        await Promise.all(
            fileNames.map(file => this.#getTemplates(file))
        );
    }
    
    
    /**
     * Returns the original <template>.
     *
     * @param {string} fileName
     * @param {string} templateId
     * @returns {Promise<HTMLTemplateElement>}
     */
    static async get(fileName, templateId) {

        const templates = await this.#getTemplates(fileName);

        const template = templates.get(templateId);

        if (!template) {
            throw new Error(
                `[Azimutant] Template "${templateId}" not found in "${fileName}.html".`
            );
        }

        return template;
    }


    /**
     * Returns a clone of the template content, ready to be inserted into the DOM.
     * 
     * @param {string} fileName
     * @param {string} templateId
     * @returns {Promise<DocumentFragment>}
     */
    static async instantiate(fileName, templateId) {

        const template = await this.get(fileName, templateId);

        return template.content.cloneNode(true);
    }


    /**
     * Clears the template cache.
     */
    static clear() {
        
        this.#cache.clear();
        this.#loading.clear();
    }


    /**
     * Tells if a template is already loaded in cache
     * 
     * @param {string} fileName
     * @returns {boolean}
     */
    static isCached(fileName) {
        
        const path = this.#getPath(fileName);
        return this.#cache.has(path);
    }


    static async #getTemplates(fileName) {

        const path = this.#getPath(fileName);

        if(!this.#cache.has(path)) {

            if (!this.#loading.has(path)) {
                this.#loading.set(path, this.#load(path));
            }

            await this.#loading.get(path);
        }
        
        return this.#cache.get(path);
    }


    static async #load(path) {
        
        try {

            const response = await fetch(path);
            
            if (!response.ok) {
                throw new Error(`[Azimutant] Impossible to load "${path}" (${response.status}).`);
            }
            
            // Handle errors when page not received
            const contentType = response.headers.get("Content-Type");
            if (!contentType?.includes("text/html")) {
                throw new Error(`[Azimutant] "${path}" is not an HTML file.`);
            }
            
            const html = await response.text();
            
            const container = document.createElement("template");
            container.innerHTML = html;
            const templateMap = new Map();

            for(const tpl of container.content.querySelectorAll("template")) {

                if(!tpl.id) {
                    console.warn(`[Azimutant] Template without id in "${path}".`);
                    continue;
                }

                if(templateMap.has(tpl.id)) {
                    console.warn(`[Azimutant] Template "${tpl.id}" already defined in "${path}".`);
                }

                templateMap.set(tpl.id, tpl);
            }
            
            if(templateMap.size === 0) {
                throw new Error(`[Azimutant] No <template> found in "${path}".`);
            }

            this.#cache.set(path, templateMap);

        } finally {

            this.#loading.delete(path);
        }
    }


    static #getPath(fileName) {
        
        return `${this.#basePath}/${fileName}.html`;
    }
}
